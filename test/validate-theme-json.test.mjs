import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import path from 'node:path';

import {
  stripLeadingComment,
  extractSchemas,
  lookup,
  translationKeys,
  checkSchema,
  validateTheme,
} from '../ci/validate-theme-json.mjs';
import { ROOT, makeTheme, scaffoldFiles } from './helpers.mjs';

const SCRIPT = path.join(ROOT, 'ci/validate-theme-json.mjs');
const section = (schema) => `<div></div>\n{% schema %}\n${JSON.stringify(schema, null, 2)}\n{% endschema %}\n`;

describe('helpers', () => {
  test('stripLeadingComment removes the generated header only', () => {
    const text = '/*\n * Generated by Shopify\n */\n{"a": "/* keep */"}';
    assert.deepEqual(JSON.parse(stripLeadingComment(text)), { a: '/* keep */' });
  });
  test('extractSchemas handles whitespace-control tags', () => {
    assert.deepEqual(extractSchemas('{%- schema -%}{"a":1}{%- endschema -%}'), ['{"a":1}']);
    assert.equal(extractSchemas('{% schema %}{}{% endschema %}{% schema %}{}{% endschema %}').length, 2);
  });
  test('lookup and translationKeys', () => {
    assert.equal(lookup({ a: { b: 'x' } }, 'a.b'), 'x');
    assert.equal(lookup({ a: 'x' }, 'a.b'), undefined);
    assert.deepEqual(translationKeys({ name: 't:a.b', settings: [{ label: 't:c' }, { label: 'plain' }] }), ['a.b', 'c']);
  });
});

describe('checkSchema', () => {
  test('flags duplicate ids in settings and blocks', () => {
    const problems = checkSchema({
      name: 'X',
      settings: [{ id: 'a' }, { id: 'a' }],
      blocks: [{ type: 'b', settings: [{ id: 'c' }, { id: 'c' }] }],
    }, null);
    assert.deepEqual(problems, ['duplicate setting id "a"', 'duplicate setting id "c" in block "b"']);
  });
  test('flags presets without a name', () => {
    assert.deepEqual(checkSchema({ name: 'X', presets: [{}] }, null), ['preset 0 has no name']);
  });
  test('flags unresolved t: keys and a missing schema locale', () => {
    assert.deepEqual(checkSchema({ name: 't:sections.x.name' }, { sections: {} }), ['translation key "t:sections.x.name" not found in default schema locale']);
    assert.match(checkSchema({ name: 't:sections.x.name' }, null)[0], /locales\/\*\.default\.schema\.json is missing/);
  });
  test('rejects a non-object schema', () => {
    assert.deepEqual(checkSchema([], null), ['schema must be a JSON object']);
  });
});

describe('validateTheme', () => {
  test('the /new-section reference scaffold is valid', () => {
    const { problems, checked } = validateTheme(makeTheme(scaffoldFiles()));
    assert.deepEqual(problems, []);
    assert.ok(checked >= 4);
  });

  test('accepts JSON templates with the Shopify comment header', () => {
    const root = makeTheme({ 'templates/index.json': '/*\n * auto-generated\n */\n{"sections":{},"order":[]}' });
    assert.deepEqual(validateTheme(root).problems, []);
  });

  test('reports broken JSON, multiple schemas and the bad example', () => {
    const root = makeTheme({
      'templates/customers/login.json': '{"sections": }',
      'sections/two.liquid': '{% schema %}{}{% endschema %}{% schema %}{}{% endschema %}',
      'sections/broken.liquid': '{% schema %}{"name": "x",}{% endschema %}',
      'sections/bad-section.liquid': readFileSync(path.join(ROOT, 'examples/bad-section.liquid'), 'utf8'),
      'blocks/ok.liquid': section({ name: 'Ok', settings: [{ id: 'a' }] }),
    });
    const problems = validateTheme(root).problems.map((p) => `${p.file}: ${p.message.split(':')[0]}`);
    assert.deepEqual(problems.sort(), [
      'sections/bad-section.liquid: duplicate setting id "color"',
      'sections/broken.liquid: invalid schema JSON',
      'sections/two.liquid: has 2 {% schema %} tags; only one is allowed',
      'templates/customers/login.json: invalid JSON',
    ]);
  });

  test('CLI exits 1 on problems and 0 on a clean theme', () => {
    const bad = spawnSync(process.execPath, [SCRIPT, makeTheme({ 'config/settings_data.json': '{' })], { encoding: 'utf8' });
    assert.equal(bad.status, 1);
    assert.match(bad.stderr, /config\/settings_data\.json: invalid JSON/);
    const good = spawnSync(process.execPath, [SCRIPT, makeTheme(scaffoldFiles())], { encoding: 'utf8' });
    assert.equal(good.status, 0, good.stderr);
    assert.match(good.stdout, /0 problem\(s\)/);
  });
});
